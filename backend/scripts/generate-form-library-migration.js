// Generate the tenant migration that seeds the system form library.
//
// Usage:  node backend/scripts/generate-form-library-migration.js > backend/migrations/tenant/008_seed_form_library.sql
//         node backend/scripts/generate-form-library-migration.js --verify
//
// WHY A GENERATOR. The library is 22 templates and 305 field definitions. Hand-copying
// that into SQL is a transcription job whose failure mode is a dropped `required: true` on
// a consent checkbox — invisible in review, consequential in use. So the migration is
// generated from the single existing source of truth
// (frontend/src/data/formTemplates.js) and `--verify` diffs the generated SQL back against
// that source, field by field.
//
// The generated file is committed. This script exists to produce it and to prove it is
// faithful, not to run at deploy time.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SOURCE = path.join(__dirname, '..', '..', 'frontend', 'src', 'data', 'formTemplates.js');
const VERIFY = process.argv.includes('--verify');
const OUTPUT = path.join(__dirname, '..', 'migrations', 'tenant', '008_seed_form_library.sql');

// --pack-forms <specialty>: emit the `formTemplates` array for a specialty pack, converted
// from the seed file's column names to the pack format. These five templates are moving out
// of the base library and into their specialty packs, and that is 71 field definitions —
// converted, not retyped, for the same reason the migration is generated.
const PACK_FORMS = (() => {
  const i = process.argv.indexOf('--pack-forms');
  return i >= 0 ? process.argv[i + 1] : null;
})();

/** Seed-file template -> pack `formTemplates` entry. Carries every column, loses nothing. */
function toPackForm(t) {
  const out = {
    slug: t.slug,
    name: t.name,
    description: t.description,
    templateType: t.template_type,
    categorySlug: t.category_slug,
    version: t.version || '1.0',
  };
  if (t.subcategory) out.subcategory = t.subcategory;
  if (t.require_signature) out.requireSignature = true;
  if (t.require_witness) out.requireWitness = true;
  if (t.intake_flow_eligible === false) out.intakeFlowEligible = false;
  if (Array.isArray(t.languages) && t.languages.length) out.languages = t.languages;
  if (Array.isArray(t.tags) && t.tags.length) out.tags = t.tags;
  if (Array.isArray(t.compliance_tags) && t.compliance_tags.length) out.complianceTags = t.compliance_tags;
  out.fields = t.fields || [];
  return out;
}

/**
 * Load the data file. It is plain object literals with no imports, so turning the two
 * `export const` declarations into a CommonJS module is enough — no transpiler, and no
 * second copy of the content to drift from the first.
 */
function loadSource() {
  const src = fs.readFileSync(SOURCE, 'utf8');
  if (/^\s*import\s/m.test(src) || /require\s*\(/.test(src)) {
    throw new Error('formTemplates.js has gained imports; this loader can no longer eval it safely');
  }
  const asCjs = src.replace(/export const/g, 'const')
    + '\nmodule.exports = { FORM_CATEGORIES, FORM_TEMPLATES };\n';
  const Module = require('module');
  const m = new Module(SOURCE);
  m._compile(asCjs, SOURCE);
  return m.exports;
}

/**
 * A stable uuid per slug.
 *
 * Deterministic on purpose: the migration runs once per tenant schema AND in `template`,
 * and provisioning copies the rows out of `template` into each new tenant. Random uuids
 * would give the same logical template a different id in every schema, so a support
 * question ("which template is this submission against?") could not be answered across
 * tenants. A uuid-v5-shaped hash of a fixed namespace plus the slug is reproducible from
 * the slug alone.
 */
function stableId(kind, slug) {
  const h = crypto.createHash('sha1').update(`aureoncare:form:${kind}:${slug}`).digest();
  const b = Buffer.from(h.subarray(0, 16));
  b[6] = (b[6] & 0x0f) | 0x50; // version 5
  b[8] = (b[8] & 0x3f) | 0x80; // RFC 4122 variant
  const hex = b.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const jsonb = (v) => (v === null || v === undefined ? 'NULL' : `${q(JSON.stringify(v))}::jsonb`);
const bool = (v) => (v === undefined || v === null ? 'NULL' : (v ? 'true' : 'false'));
const int = (v) => (v === undefined || v === null ? 'NULL' : String(Number(v)));

function generate({ FORM_CATEGORIES, FORM_TEMPLATES }) {
  const out = [];
  out.push(`-- Tenant migration 008: seed the system form library
--
-- GENERATED by backend/scripts/generate-form-library-migration.js from
-- frontend/src/data/formTemplates.js. Do not hand-edit: regenerate, and run the
-- generator's --verify to diff it back against the source field by field.
--
-- WHY THIS EXISTS. form_templates has been empty in every tenant since the form module
-- shipped, so FormManagementView fell back to rendering the frontend's seed array and sent
-- forms to patients with \`template_id: null\`. A signed consent therefore had no durable
-- link to the template version the patient actually saw, and \`template_version\` was
-- copied from whatever happened to be in the JavaScript bundle that day. Putting the
-- library in the database is what fixes that.
--
-- Stamped source_pack = 'base': these are the product's own universal templates, not a
-- specialty choice, so the specialty-pack machinery protects them on upgrade
-- (is_customised is honoured) without a pack having to be chosen first.
--
-- Ids are deterministic (uuid v5 of the slug), so the same logical template has the same
-- id in every tenant and in \`template\`. Newly provisioned tenants get these rows by
-- copying them out of \`template\` in services/tenantProvisioning.js — provision_schema
-- clones structure only, never data.
--
-- Unqualified names: the runner sets search_path per tenant schema and for \`template\`.
`);

  out.push(`-- ── categories (${FORM_CATEGORIES.length}) ──────────────────────────────────────────────────────\n`);
  out.push('INSERT INTO form_categories (id, name, slug, sort_order, is_active) VALUES');
  out.push(FORM_CATEGORIES.map((c, i) =>
    `  (${q(stableId('category', c.slug))}, ${q(c.name)}, ${q(c.slug)}, ${int((i + 1) * 10)}, true)`
  ).join(',\n') + '\nON CONFLICT (slug) DO NOTHING;\n');

  out.push(`-- ── templates (${FORM_TEMPLATES.length}) ───────────────────────────────────────────────────────\n`);

  for (const t of FORM_TEMPLATES) {
    const catId = FORM_CATEGORIES.some((c) => c.slug === t.category_slug)
      ? q(stableId('category', t.category_slug))
      : 'NULL';
    out.push(`-- ${t.name} (${(t.fields || []).length} fields)
INSERT INTO form_templates (
  id, name, slug, description, category_id, category_slug, subcategory, template_type,
  is_system_template, is_active, version, version_number, fields, require_signature,
  require_witness, allow_pdf_export, languages, tags, intake_flow_eligible, specialty,
  compliance_tags, source_pack, source_pack_version, is_customised
) VALUES (
  ${q(stableId('template', t.slug))}, ${q(t.name)}, ${q(t.slug)}, ${q(t.description)},
  ${catId}, ${q(t.category_slug)}, ${q(t.subcategory)}, ${q(t.template_type)},
  true, true, ${q(t.version || '1.0')}, ${int(parseInt(t.version, 10) || 1)},
  ${jsonb(t.fields || [])}, ${bool(t.require_signature)},
  ${bool(t.require_witness)}, true, ${jsonb(t.languages || ['en'])},
  ${jsonb(t.tags || [])}, ${bool(t.intake_flow_eligible)}, ${q(t.specialty || null)},
  ${jsonb(t.compliance_tags || [])}, 'base', 1, false
) ON CONFLICT (slug) DO NOTHING;
`);
  }

  out.push(`-- ── verification ───────────────────────────────────────────────────────────────────
DO $seeded$
DECLARE cats int; tmpls int; flds int;
BEGIN
  SELECT count(*) INTO cats  FROM form_categories;
  SELECT count(*) INTO tmpls FROM form_templates WHERE source_pack = 'base';
  SELECT COALESCE(SUM(jsonb_array_length(fields)), 0) INTO flds
    FROM form_templates WHERE source_pack = 'base';
  IF tmpls < ${FORM_TEMPLATES.length} OR flds < ${FORM_TEMPLATES.reduce((n, t) => n + (t.fields || []).length, 0)} THEN
    RAISE WARNING '008 in %: expected ${FORM_TEMPLATES.length} templates and ${FORM_TEMPLATES.reduce((n, t) => n + (t.fields || []).length, 0)} fields, found % and %',
      current_schema(), tmpls, flds;
  END IF;
END $seeded$;
`);

  return out.join('\n');
}

/**
 * Diff the GENERATED SQL back against the source, so the claim "faithful" is checked
 * rather than asserted. Parses the jsonb literals out of the SQL and compares every field
 * id, type and required flag.
 */
function verify({ FORM_TEMPLATES, FORM_CATEGORIES }) {
  if (!fs.existsSync(OUTPUT)) {
    console.error(`FAIL: ${path.relative(process.cwd(), OUTPUT)} does not exist — generate it first`);
    return 1;
  }
  const sql = fs.readFileSync(OUTPUT, 'utf8');
  let problems = 0;
  const fail = (m) => { console.error(`  FAIL  ${m}`); problems++; };

  for (const c of FORM_CATEGORIES) {
    if (!sql.includes(`'${c.slug}'`)) fail(`category ${c.slug} missing from the SQL`);
  }

  // Pull each template's fields jsonb back out of the generated SQL.
  const blocks = sql.split('INSERT INTO form_templates (').slice(1);
  if (blocks.length !== FORM_TEMPLATES.length) {
    fail(`SQL has ${blocks.length} template inserts, source has ${FORM_TEMPLATES.length}`);
  }

  for (const t of FORM_TEMPLATES) {
    const block = blocks.find((b) => b.includes(`'${t.slug}'`));
    if (!block) { fail(`template ${t.slug} missing from the SQL`); continue; }

    const m = block.match(/'(\[.*?\])'::jsonb,\s*(?:true|false|NULL)/s);
    if (!m) { fail(`${t.slug}: could not recover the fields array from the SQL`); continue; }
    let parsed;
    try {
      parsed = JSON.parse(m[1].replace(/''/g, "'"));
    } catch (e) {
      fail(`${t.slug}: generated fields jsonb does not parse (${e.message})`);
      continue;
    }

    const want = t.fields || [];
    if (parsed.length !== want.length) {
      fail(`${t.slug}: ${parsed.length} fields in SQL, ${want.length} in source`);
      continue;
    }
    for (let i = 0; i < want.length; i++) {
      const a = want[i];
      const b = parsed[i];
      if (a.id !== b.id) fail(`${t.slug}[${i}]: id ${a.id} became ${b.id}`);
      if (a.type !== b.type) fail(`${t.slug}[${i}] ${a.id}: type ${a.type} became ${b.type}`);
      if (Boolean(a.required) !== Boolean(b.required)) {
        fail(`${t.slug}[${i}] ${a.id}: required ${Boolean(a.required)} became ${Boolean(b.required)}`);
      }
      if (a.label !== b.label) fail(`${t.slug}[${i}] ${a.id}: label changed`);
      if (JSON.stringify(a.options || null) !== JSON.stringify(b.options || null)) {
        fail(`${t.slug}[${i}] ${a.id}: options changed`);
      }
    }
    // require_signature on a consent form is not cosmetic.
    const sig = /is_system_template[\s\S]*?::jsonb,\s*(true|false),/.exec(block);
    if (sig && Boolean(t.require_signature) !== (sig[1] === 'true')) {
      fail(`${t.slug}: require_signature ${Boolean(t.require_signature)} became ${sig[1]}`);
    }
  }

  const totalFields = FORM_TEMPLATES.reduce((n, t) => n + (t.fields || []).length, 0);
  if (problems === 0) {
    console.log(`ok — ${FORM_TEMPLATES.length} templates, ${totalFields} fields and `
      + `${FORM_CATEGORIES.length} categories match the source exactly`);
    return 0;
  }
  console.error(`\n${problems} discrepancy/ies between the generated SQL and the source.`);
  return 1;
}

const data = loadSource();
if (PACK_FORMS) {
  // The seed file spells it `pediatrics`; the taxonomy (and the rest of the product)
  // spells the specialty `paediatrics`, consistent with orthopaedics and anaesthesiology.
  // Accept either so the caller can ask by the taxonomy code.
  const alias = { paediatrics: 'pediatrics' };
  const want = alias[PACK_FORMS] || PACK_FORMS;
  const forms = data.FORM_TEMPLATES.filter((t) => t.specialty === want).map(toPackForm);
  if (!forms.length) {
    console.error(`No templates in the seed file carry specialty "${want}"`);
    process.exit(1);
  }
  process.stdout.write(JSON.stringify(forms, null, 2) + '\n');
} else if (VERIFY) {
  process.exit(verify(data));
} else {
  process.stdout.write(generate(data));
}
