// Build backend/scripts/manual/apply-specialty-packs.sql — the SQL-editor equivalent of
// `npm run packs:load`.
//
// Usage:  node backend/scripts/build-manual-specialty-packs.js > backend/scripts/manual/apply-specialty-packs.sql
//
// WHY THIS EXISTS. The specialty packs are JSON files published by a node script. Anyone
// who cannot run node against the database — the whole reason the manual scripts exist —
// had no way to publish them, so `public.specialty_packs` stayed empty and every specialty
// in the setup wizard read "no starter content yet". The wizard worked; there was simply
// nothing to offer.
//
// Each pack is written in two stages: the pack WITHOUT its form templates, then one UPDATE
// per form template appending it to the definition. That is not fussiness — a whole pack as
// a single quoted literal reaches 17 KB, and the Supabase SQL editor has already rejected
// this project's SQL once for exactly that (see scripts/manual/README.md). Split this way
// no literal exceeds about 4 KB, the same scale as tenant/008's, which it accepts.
//
// Re-running is safe and produces the same result: the first statement per pack REPLACES
// the definition (resetting formTemplates), and the appends then rebuild it in order.
//
// A pack a clinician has already approved is left completely alone — both stages carry the
// same guard — because its approval is attached to that exact content.

const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'data', 'specialty-packs');
const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();

const lit = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const str = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const out = [];
out.push(`-- Publish the specialty packs into public.specialty_packs.
--
-- GENERATED by backend/scripts/build-manual-specialty-packs.js from
-- backend/data/specialty-packs/*.json. Regenerate rather than hand-editing.
--
-- Equivalent to: npm run packs:load
--
-- Run it AFTER apply-global-085.sql, which creates public.specialties and
-- public.specialty_packs. Without this step the setup wizard lists every specialty as
-- having "no starter content yet" — the wizard is fine, there is simply nothing published
-- for it to offer.
--
-- Each pack is written as one INSERT for everything except its form templates, then one
-- UPDATE per form template. A whole pack as a single literal runs to 17 KB and the
-- Supabase SQL editor has rejected this project's SQL for that before; split this way no
-- literal passes about 4 KB.
--
-- Safe to re-run: the INSERT replaces the definition and the appends rebuild it, so the
-- end state is the same however many times it runs.
--
-- A pack a clinician has marked approved is skipped entirely — approval is attached to
-- that exact content, so publishing over it would make the sign-off a lie. Bump the
-- version instead.

BEGIN;

SET search_path TO public;
`);

let packCount = 0;
let formCount = 0;

for (const file of files) {
  const pack = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));
  const forms = Array.isArray(pack.formTemplates) ? pack.formTemplates : [];
  const base = { ...pack };
  delete base.formTemplates;
  packCount++;
  formCount += forms.length;

  out.push(`-- ─── ${pack.code} v${pack.version} — ${forms.length} form template(s) ───────────────────────────`);
  out.push(`INSERT INTO public.specialty_packs (code, version, label, definition, is_active)
VALUES (${str(pack.code)}, ${pack.version}, ${str(pack.label)}, ${lit(base)}, true)
ON CONFLICT (code, version) DO UPDATE
   SET label = EXCLUDED.label,
       definition = EXCLUDED.definition,
       is_active = true,
       updated_at = CURRENT_TIMESTAMP
 WHERE public.specialty_packs.clinical_review_status <> 'approved';
`);

  forms.forEach((form, i) => {
    out.push(`-- ${pack.code} v${pack.version}: form ${i + 1}/${forms.length} — ${form.slug} (${(form.fields || []).length} fields)
UPDATE public.specialty_packs
   SET definition = jsonb_set(definition, '{formTemplates}',
         COALESCE(definition -> 'formTemplates', '[]'::jsonb) || ${lit([form])})
 WHERE code = ${str(pack.code)} AND version = ${pack.version}
   AND clinical_review_status <> 'approved';
`);
  });
}

out.push(`COMMIT;

-- ─── verification ──────────────────────────────────────────────────────────────────
DO $verify$
DECLARE
  n_packs   int;
  n_forms   int;
  n_pending int;
  r         record;
BEGIN
  SELECT count(*) INTO n_packs FROM public.specialty_packs;
  SELECT COALESCE(SUM(jsonb_array_length(definition -> 'formTemplates')), 0) INTO n_forms
    FROM public.specialty_packs WHERE definition ? 'formTemplates';
  SELECT count(*) INTO n_pending FROM public.specialty_packs
   WHERE is_active AND clinical_review_status = 'pending';

  IF n_packs < ${packCount} OR n_forms < ${formCount} THEN
    RAISE WARNING 'expected at least ${packCount} pack(s) carrying ${formCount} form template(s), found % and %',
      n_packs, n_forms;
  ELSE
    RAISE NOTICE 'verified: % pack(s) published carrying % form template(s)', n_packs, n_forms;
  END IF;

  -- Every pack a specialty can be chosen by, so a missing taxonomy row is caught here
  -- rather than as an empty wizard.
  FOR r IN
    SELECT p.code FROM public.specialty_packs p
     LEFT JOIN public.specialties s ON s.code = p.code
     WHERE s.code IS NULL
  LOOP
    RAISE WARNING 'pack "%" has no row in public.specialties — the wizard cannot offer it', r.code;
  END LOOP;

  IF n_pending > 0 THEN
    RAISE NOTICE '% pack(s) await clinical review. They can be applied, but the wizard will say the content is an engineering draft.', n_pending;
    RAISE NOTICE 'A clinician signs one off with: UPDATE public.specialty_packs SET clinical_review_status = ''approved'', reviewed_by = ''name'', reviewed_at = now() WHERE code = ''dentistry'' AND version = 1;';
  END IF;
END $verify$;
`);

process.stdout.write(out.join('\n'));
