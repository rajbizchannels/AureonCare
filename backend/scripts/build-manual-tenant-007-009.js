// Build backend/scripts/manual/apply-tenant-migrations-007-009.sql.
//
// Usage:  node backend/scripts/build-manual-tenant-007-009.js > backend/scripts/manual/apply-tenant-migrations-007-009.sql
//
// WHY A BUILDER. tenant/008 is 283 field definitions inside jsonb literals. The other
// manual scripts run their DDL from inside a DO loop via `EXECUTE '...'`, which would mean
// doubling every single quote in all of it — a transcription job with no upside. So this
// script embeds 008's body VERBATIM at the top level, under a search_path pinned to
// `template`, and then fans the rows out of `template` into every tenant schema with a
// plain INSERT ... SELECT. No escaping, nothing retyped, and the fan-out is the same copy
// that services/tenantProvisioning.js and scripts/repair-form-library.js already do.

const fs = require('fs');
const path = require('path');

const TENANT_DIR = path.join(__dirname, '..', 'migrations', 'tenant');
const body008 = fs.readFileSync(path.join(TENANT_DIR, '008_seed_form_library.sql'), 'utf8')
  // Drop the file's own leading comment block; this script writes its own header.
  .replace(/^(--[^\n]*\n)+/, '')
  .trim();

// The schema list every loop uses, matching apply-tenant-migrations.sql.
const SCHEMAS = `    SELECT schema_name FROM control.tenants
     WHERE schema_name IS NOT NULL AND status <> 'suspended'
    UNION SELECT 'template'
    UNION SELECT nspname FROM pg_namespace WHERE nspname LIKE 'tenant~_%' ESCAPE '~'`;

const PROVENANCE_TABLES = [
  'service_categories', 'healthcare_offerings', 'appointment_types',
  'form_templates', 'inventory_categories',
];

const MOVED_SLUGS = [
  'phq9-depression-screening', 'gad7-anxiety-screening', 'behavioral-health-intake',
  'pediatric-wellness-intake', 'dental-health-history',
];

process.stdout.write(`-- Apply TENANT migrations 007, 008 and 009 across every tenant schema.
--
-- GENERATED by backend/scripts/build-manual-tenant-007-009.js. Regenerate rather than
-- hand-editing; 008's body is embedded verbatim from the migration file.
--
-- Companion to apply-tenant-migrations.sql, which covers 001-006. Run that first.
--
-- Why the raw files fail when pasted into a SQL editor: tenant/*.sql use UNQUALIFIED table
-- names on purpose, because the runner sets search_path per tenant before executing each
-- one. Run them directly and you get, exactly as reported:
--     ERROR: 42P01: relation "form_categories" does not exist     (008, line 27)
--     ERROR: 42P01: relation "form_templates" does not exist      (009, in the DO block)
-- The SQL is fine; it is looking in \`public\`, and since migration 066 the tenant tables
-- are not there.
--
-- Same editor constraints as the other manual scripts: no nested dollar quoting, and every
-- dollar-quote tag is letters only (prov, seeded, fan, move, verify) because the
-- Supabase SQL editor's tag matcher does not recognise digits.
--
-- 008 is embedded at the TOP LEVEL under a search_path pinned to \`template\`, so its jsonb
-- literals need no escaping. The rows are then copied out of \`template\` into every tenant
-- schema — the same copy that provisioning and scripts/repair-form-library.js perform.
--
-- Safe to re-run: each schema's own ledger is consulted first.

BEGIN;

-- ═══════════════════════════════════════════════════════════════════════════
-- 007.  Provenance columns for specialty-pack-seeded rows
-- ═══════════════════════════════════════════════════════════════════════════

DO \$prov\$
DECLARE
  sch  text;
  tbl  text;
  done boolean;
  n    int := 0;
BEGIN
  FOR sch IN
${SCHEMAS}
  LOOP
    CONTINUE WHEN to_regclass(format('%I.patients', sch)) IS NULL;

    EXECUTE format('CREATE TABLE IF NOT EXISTS %I.schema_migrations (version integer PRIMARY KEY, name text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now())', sch);
    EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I.schema_migrations WHERE version = 7)', sch) INTO done;
    CONTINUE WHEN done;

    FOREACH tbl IN ARRAY ARRAY[${PROVENANCE_TABLES.map((t) => `'${t}'`).join(', ')}] LOOP
      CONTINUE WHEN to_regclass(format('%I.%I', sch, tbl)) IS NULL;
      EXECUTE format('ALTER TABLE %I.%I ADD COLUMN IF NOT EXISTS source_pack varchar(60)', sch, tbl);
      EXECUTE format('ALTER TABLE %I.%I ADD COLUMN IF NOT EXISTS source_pack_version integer', sch, tbl);
      EXECUTE format('ALTER TABLE %I.%I ADD COLUMN IF NOT EXISTS is_customised boolean NOT NULL DEFAULT false', sch, tbl);
      EXECUTE format('ALTER TABLE %I.%I ADD COLUMN IF NOT EXISTS department_id uuid', sch, tbl);
      EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I.%I (source_pack) WHERE source_pack IS NOT NULL',
                     'idx_' || tbl || '_pack', sch, tbl);
    END LOOP;

    EXECUTE format('INSERT INTO %I.schema_migrations (version, name) VALUES (7, %L)', sch, '007_pack_provenance.sql');
    n := n + 1;
  END LOOP;
  RAISE NOTICE '007: applied to % schema(s)', n;
END \$prov\$;

-- ═══════════════════════════════════════════════════════════════════════════
-- 008.  Seed the system form library — into \`template\` first
-- ═══════════════════════════════════════════════════════════════════════════
--
-- The body below is tenant/008 verbatim. search_path is pinned to \`template\` so its
-- unqualified names resolve there and its jsonb literals need no escaping. SET LOCAL is
-- transaction-scoped, so it reverts at COMMIT.

SET LOCAL search_path TO template, public, control;

${body008}

SET LOCAL search_path TO public;

-- Take the five specialty forms back out of \`template\` straight away, BEFORE the fan-out
-- below copies from it.
--
-- This is unconditional, unlike the per-tenant pass further down, and it has to be. The
-- 008 body above is plain top-level SQL with no ledger guard — it cannot have one without
-- escaping all 283 field definitions — so a SECOND run of this script re-inserts the five
-- into \`template\` (they are absent by then, so ON CONFLICT does not fire) while the
-- ledger-guarded 009 pass skips it. The script would then leave \`template\` holding 22
-- base templates instead of 17, and every tenant provisioned afterwards would silently get
-- the five back, undoing the move. Repeating the removal here makes the end state the same
-- however many times the script is run.
--
-- No guards are needed for \`template\` itself: it is the structural golden copy and holds
-- no submissions, no offerings and nothing a practice has edited.
DELETE FROM template.form_templates
 WHERE source_pack = 'base'
   AND slug IN (${MOVED_SLUGS.map((x) => `'${x}'`).join(', ')});

INSERT INTO template.schema_migrations (version, name)
VALUES (8, '008_seed_form_library.sql') ON CONFLICT (version) DO NOTHING;
INSERT INTO template.schema_migrations (version, name)
VALUES (9, '009_specialty_forms_move_to_packs.sql') ON CONFLICT (version) DO NOTHING;

-- ═══════════════════════════════════════════════════════════════════════════
-- 008 (continued).  Copy the library from \`template\` into every tenant
-- ═══════════════════════════════════════════════════════════════════════════

DO \$fan\$
DECLARE
  sch  text;
  done boolean;
  n    int := 0;
BEGIN
  FOR sch IN
${SCHEMAS}
  LOOP
    CONTINUE WHEN sch = 'template';
    CONTINUE WHEN to_regclass(format('%I.form_templates', sch)) IS NULL;

    EXECUTE format('CREATE TABLE IF NOT EXISTS %I.schema_migrations (version integer PRIMARY KEY, name text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now())', sch);
    EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I.schema_migrations WHERE version = 8)', sch) INTO done;
    CONTINUE WHEN done;

    EXECUTE format(
      'INSERT INTO %I.form_categories (id, name, slug, description, color, icon, parent_id, sort_order, is_active)
       SELECT id, name, slug, description, color, icon, parent_id, sort_order, is_active
         FROM template.form_categories
       ON CONFLICT (slug) DO NOTHING', sch);

    EXECUTE format(
      'INSERT INTO %I.form_templates
         (id, name, slug, description, category_id, category_slug, subcategory, template_type,
          is_system_template, is_active, version, version_number, fields, settings,
          require_signature, require_witness, allow_pdf_export, languages, tags,
          intake_flow_eligible, specialty, compliance_tags, source_pack, source_pack_version,
          is_customised)
       SELECT id, name, slug, description, category_id, category_slug, subcategory, template_type,
              is_system_template, is_active, version, version_number, fields, settings,
              require_signature, require_witness, allow_pdf_export, languages, tags,
              intake_flow_eligible, specialty, compliance_tags, source_pack, source_pack_version,
              false
         FROM template.form_templates
        WHERE source_pack = ''base''
       ON CONFLICT (slug) DO NOTHING', sch);

    EXECUTE format('INSERT INTO %I.schema_migrations (version, name) VALUES (8, %L)', sch, '008_seed_form_library.sql');
    n := n + 1;
  END LOOP;
  RAISE NOTICE '008: form library copied into % schema(s)', n;
END \$fan\$;

-- ═══════════════════════════════════════════════════════════════════════════
-- 009.  Hand five specialty forms over to their specialty packs
-- ═══════════════════════════════════════════════════════════════════════════
--
-- A row is kept, not deleted, when the practice has edited it, when a form_submission
-- points at it, or when a healthcare_offering uses it as its consent form. Everything is
-- schema-qualified through format(): a static PL/pgSQL statement is plan-cached and would
-- not respect a search_path changed inside the loop.

DO \$move\$
DECLARE
  sch       text;
  s         text;
  done      boolean;
  tpl_id    uuid;
  tpl_cust  boolean;
  tpl_pack  text;
  refs      bigint;
  removed   int;
  kept      int;
  n_schemas int := 0;
BEGIN
  FOR sch IN
${SCHEMAS}
  LOOP
    CONTINUE WHEN to_regclass(format('%I.form_templates', sch)) IS NULL;

    EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I.schema_migrations WHERE version = 9)', sch) INTO done;
    CONTINUE WHEN done;

    removed := 0;
    kept := 0;

    FOREACH s IN ARRAY ARRAY[${MOVED_SLUGS.map((x) => `'${x}'`).join(', ')}] LOOP
      EXECUTE format('SELECT id, is_customised, source_pack FROM %I.form_templates WHERE slug = %L', sch, s)
        INTO tpl_id, tpl_cust, tpl_pack;
      CONTINUE WHEN tpl_id IS NULL;

      IF tpl_pack IS DISTINCT FROM 'base' THEN kept := kept + 1; CONTINUE; END IF;
      IF tpl_cust THEN
        RAISE NOTICE '009 in %: keeping % — the practice has edited it', sch, s;
        kept := kept + 1; CONTINUE;
      END IF;

      EXECUTE format('SELECT count(*) FROM %I.form_submissions WHERE template_id = %L', sch, tpl_id) INTO refs;
      IF refs > 0 THEN
        RAISE NOTICE '009 in %: keeping % — % submission(s) reference it', sch, s, refs;
        kept := kept + 1; CONTINUE;
      END IF;

      EXECUTE format('SELECT count(*) FROM %I.healthcare_offerings WHERE consent_form_id = %L', sch, tpl_id) INTO refs;
      IF refs > 0 THEN
        RAISE NOTICE '009 in %: keeping % — % offering(s) use it as a consent form', sch, s, refs;
        kept := kept + 1; CONTINUE;
      END IF;

      EXECUTE format('DELETE FROM %I.form_templates WHERE id = %L', sch, tpl_id);
      removed := removed + 1;
    END LOOP;

    EXECUTE format('INSERT INTO %I.schema_migrations (version, name) VALUES (9, %L)', sch, '009_specialty_forms_move_to_packs.sql');
    n_schemas := n_schemas + 1;
  END LOOP;
  RAISE NOTICE '009: processed % schema(s)', n_schemas;
END \$move\$;

COMMIT;

-- ═══════════════════════════════════════════════════════════════════════════
-- Verification. Silence means every provisioned schema is current.
-- ═══════════════════════════════════════════════════════════════════════════

DO \$verify\$
DECLARE
  sch     text;
  got     text;
  tmpls   bigint;
  missing int := 0;
  thin    int := 0;
  expect  bigint;
BEGIN
  SELECT count(*) INTO expect FROM template.form_templates WHERE source_pack = 'base';

  FOR sch IN
${SCHEMAS}
  LOOP
    CONTINUE WHEN to_regclass(format('%I.patients', sch)) IS NULL;

    EXECUTE format('SELECT string_agg(version::text, '','' ORDER BY version) FROM %I.schema_migrations WHERE version BETWEEN 1 AND 9', sch) INTO got;
    IF got IS DISTINCT FROM '1,2,3,4,5,6,7,8,9' THEN
      RAISE WARNING 'incomplete: % has [%], expected 1..9', sch, COALESCE(got, 'none');
      missing := missing + 1;
    END IF;

    EXECUTE format('SELECT count(*) FROM %I.form_templates WHERE source_pack = ''base''', sch) INTO tmpls;
    IF tmpls < expect THEN
      RAISE WARNING 'form library short: % has % of % base templates', sch, tmpls, expect;
      thin := thin + 1;
    END IF;
  END LOOP;

  IF missing = 0 AND thin = 0 THEN
    RAISE NOTICE 'verified: every provisioned tenant schema has tenant migrations 1 to 9 and the full form library (% templates)', expect;
  END IF;
END \$verify\$;
`);
